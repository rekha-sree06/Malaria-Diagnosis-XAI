def evaluate_dataset(dataset, dataset_name="Validation"):
    steps = tf.data.experimental.cardinality(dataset).numpy()
    if steps <= 0:
        steps = 0
        for _ in dataset:
            steps += 1
    print(f"{dataset_name} steps (batches):", steps)

    predictions = model.predict(dataset, steps=steps, verbose=1)
    y_pred = (predictions > 0.5).astype("int32").flatten()
    y_true = np.concatenate([y for x, y in dataset], axis=0).flatten()

    print(f"{dataset_name} Classification Report:")
    print(classification_report(y_true, y_pred, target_names=classes))

    plt.figure(figsize=(7, 5))
    sns.heatmap(confusion_matrix(y_true, y_pred), annot=True, fmt="d", cmap='Blues',
                xticklabels=classes, yticklabels=classes)
    plt.title(f"{dataset_name} Confusion Matrix", fontsize=16, color='darkgreen')
    plt.xlabel("Predicted Label", fontsize=14)
    plt.ylabel("True Label", fontsize=14)
    plt.show()

    fpr, tpr, _ = roc_curve(y_true, predictions)
    roc_auc = auc(fpr, tpr)
    plt.figure(figsize=(7, 6))
    plt.plot(fpr, tpr, lw=2, label=f'ROC curve (AUC = {roc_auc:.2f})')
    plt.plot([0, 1], [0, 1], lw=2, linestyle='--')
    plt.title(f"{dataset_name} ROC Curve", fontsize=16, color='purple')
    plt.xlabel("False Positive Rate", fontsize=14)
    plt.ylabel("True Positive Rate", fontsize=14)
    plt.legend(fontsize=12)
    plt.grid(True, linestyle='--', alpha=0.6)
    plt.show()

