"""##**BUILD THE INCEPTION-RESNET V2-BASED MODEL**
In this cell, the Inception-ResNet V2 model is loaded with pre-trained ImageNet weights while excluding its top classification layers, using an input size of 224×224×3. The base model's layers are frozen initially to preserve the learned features, and a custom classifier is then appended on top. This classifier begins with a GlobalAveragePooling2D layer that aggregates the spatial features, followed by a Dense layer with 1024 units and ReLU activation to learn high-level representations, a Dropout layer with a 0.5 dropout rate to reduce overfitting, and a final Dense layer with a sigmoid activation function to perform binary classification. The resulting model, named "InceptionResNetV2_Transfer", comprises approximately 55.9 million parameters in total; however, only about 1.57 million parameters are trainable, with the remainder (approximately 54.3 million) being frozen. This setup leverages the robust feature extraction capabilities of Inception-ResNet V2 while allowing the new classifier layers to adapt to the specific task.
"""

###############################################################################
# CELL 7: BUILD THE INCEPTION-RESNET V2-BASED MODEL
###############################################################################
IMG_HEIGHT = 224
IMG_WIDTH  = 224

# Load InceptionResNetV2 without the top layers, using ImageNet weights.
base_model = InceptionResNetV2(weights='imagenet', include_top=False, input_shape=(IMG_HEIGHT, IMG_WIDTH, 3))
# Freeze the base model initially.
for layer in base_model.layers:
    layer.trainable = False

x = base_model.output
x = GlobalAveragePooling2D(name="global_avg_pool")(x)
x = Dense(1024, activation='relu', name="dense_1024")(x)
x = Dropout(0.5, name="dropout")(x)
predictions = Dense(1, activation='sigmoid', name="output")(x)

model = Model(inputs=base_model.input, outputs=predictions, name="InceptionResNetV2_Transfer")
model.summary()

"""##**CUSTOM CALLBACKS & TRAINING THE MODEL (INCLUDING TEST EVALUATION)**
This cell defines custom callbacks to monitor and evaluate the model's performance during training. First, it defines the `PrintEpochMetrics` callback, which prints the training and validation loss and accuracy at the end of each epoch. This helps track how well the model is learning over time. Next, the `TestEvaluationCallback` is defined; it evaluates the model on the test dataset at the end of every epoch and stores the corresponding loss and accuracy values. This callback prints the test metrics for each epoch, providing insight into the model’s generalization on unseen data. Finally, a learning rate scheduler is set up using `ReduceLROnPlateau`, which monitors the validation loss and reduces the learning rate if no improvement is observed, helping the model converge more effectively. Together, these callbacks ensure comprehensive tracking of model performance across training, validation, and test sets throughout the training process.
"""

###############################################################################
# CELL 8: CUSTOM CALLBACKS & TRAINING THE MODEL (INCLUDING TEST EVALUATION)
###############################################################################
# Callback to print epoch metrics.
class PrintEpochMetrics(tf.keras.callbacks.Callback):
    def on_epoch_end(self, epoch, logs=None):
        logs = logs or {}
        train_acc = logs.get('accuracy')
        val_acc   = logs.get('val_accuracy')
        train_loss = logs.get('loss')
        val_loss   = logs.get('val_loss')
        print(f"Epoch {epoch+1}:")
        print(f"  Training Loss: {train_loss:.4f}, Training Accuracy: {train_acc:.4f}")
        if val_loss is not None and val_acc is not None:
            print(f"  Validation Loss: {val_loss:.4f}, Validation Accuracy: {val_acc:.4f}")

print_metrics_cb = PrintEpochMetrics()

# Callback to evaluate test set metrics at the end of each epoch.
class TestEvaluationCallback(tf.keras.callbacks.Callback):
    def __init__(self, test_ds):
        super(TestEvaluationCallback, self).__init__()
        self.test_ds = test_ds
        self.test_acc = []
        self.test_loss = []

    def on_epoch_end(self, epoch, logs=None):
        loss, acc = self.model.evaluate(self.test_ds, verbose=0)
        self.test_loss.append(loss)
        self.test_acc.append(acc)
        print(f"Test metrics after epoch {epoch+1}: loss = {loss:.4f}, acc = {acc:.4f}")

test_eval_cb = TestEvaluationCallback(test_ds)

# Use only ReduceLROnPlateau and the custom print callbacks (no early stopping).
reduce_lr  = ReduceLROnPlateau(monitor='val_loss', factor=0.1, patience=2, min_lr=1e-7)

