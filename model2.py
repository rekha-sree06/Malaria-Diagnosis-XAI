file_paths = []
labels = []
for i, cls in enumerate(classes):
    cls_dir = os.path.join(data_dir, cls)
    # Load only PNG files.
    paths = glob.glob(os.path.join(cls_dir, "*.png"))
    file_paths.extend(paths)
    labels.extend([i] * len(paths))

